"""Rotation/connection acceptance gates against the owner-supplied mutants.

The positive geometry is independently reconstructed from the permitted
truth-input functions. JSON certificates were generated by the exact script
archived under the external acceptance-repair evidence directory. The
oracle here is the stated exact fixture geometry and the lemma's algebraic
endpoint bound, not any production contact-engine implementation.
"""

import json
from fractions import Fraction as F
from pathlib import Path

from t2b_independent_cage_verifier import verify_cage
from t2b_truth_geometry import diamond_plates, instance_json, low_room


DATA = Path(__file__).parent / "data" / "t2b_acceptance"


def load_rotation_case(name):
    with open(DATA / (name + ".instance.json"), encoding="utf-8") as handle:
        instance = json.load(handle)
    with open(DATA / (name + ".cert.json"), encoding="utf-8") as handle:
        certificate = json.load(handle)
    return instance, certificate


def independent_asymmetric_instance():
    """Diamond plus one first-quadrant corner; not centrally symmetric."""
    moving = ((F(1), F(0)), (F(3, 4), F(3, 4)), (F(0), F(1)),
              (F(-1), F(0)), (F(0), F(-1)))
    _, obstacles = diamond_plates()
    return instance_json(moving, obstacles)


def assert_rejection(name, condition, check):
    instance, certificate = load_rotation_case(name)
    result = verify_cage(instance, certificate)
    assert result["valid"] is False, result
    assert result["condition"] == condition, result
    assert result["where"]["check"] == check, result
    return result


def test_nonzero_chart_centers_with_used_rotated_kernels_accept():
    """V106/V204: nonzero centers occur in kernels actually used by V4."""
    instance, certificate = load_rotation_case("asymmetric_closed")
    assert instance == independent_asymmetric_instance()
    breakpoints = certificate["chain"]["breakpoints"]
    used = 0
    for index, interval in enumerate(certificate["intervals"]):
        middle = (F(breakpoints[index]) + F(breakpoints[index + 1])) / 2
        parameter = middle
        if middle > 1:
            parameter = middle - 2
        assert parameter != 0
        for kernel, _ in interval["witnesses"]:
            if interval["pieces"][kernel]["kind"] == "rotated":
                used += 1
    assert used > 0
    result = verify_cage(instance, certificate)
    assert result["valid"] is True, result


def test_noncentrally_symmetric_body_chart_two_rotated_kernels_accept():
    """V205: a sign reversal cannot hide behind a centrally symmetric body."""
    instance, certificate = load_rotation_case("asymmetric_closed")
    assert instance == independent_asymmetric_instance()
    vertices = set()
    for x, y in instance["moving"]:
        vertices.add((F(x), F(y)))
    assert (F(3, 4), F(3, 4)) in vertices
    assert (F(-3, 4), F(-3, 4)) not in vertices
    used = 0
    for interval in certificate["intervals"][32:]:
        for kernel, _ in interval["witnesses"]:
            if interval["pieces"][kernel]["kind"] == "rotated":
                used += 1
    assert used > 0
    result = verify_cage(instance, certificate)
    assert result["valid"] is True, result


def test_two_interval_low_room_capped_chain_accepts():
    """N=2 makes the two cap-side interval identities observably distinct."""
    instance, certificate = load_rotation_case("split_low_room")
    moving, obstacles = low_room()
    assert instance == instance_json(moving, obstacles)
    assert certificate["chain"]["breakpoints"] == ["-1/23", "0", "1/23"]
    assert len(certificate["intervals"]) == 2
    assert certificate["caps"][0]["at"] == 0
    assert certificate["caps"][1]["at"] == 2
    first = certificate["intervals"][0]["pieces"][0]["polygon"]
    second = certificate["intervals"][1]["pieces"][0]["polygon"]
    assert first != second
    result = verify_cage(instance, certificate)
    assert result["valid"] is True, result


def test_internal_and_closed_seam_exact_connections_accept():
    """V507: seam lambda=3 must use the final interval's chart, not I_1."""
    instance, certificate = load_rotation_case("asymmetric_closed")
    assert instance == independent_asymmetric_instance()
    count = len(certificate["intervals"])
    assert certificate["links"][0]["at"] == 1
    assert certificate["links"][-1]["at"] == count
    for link in certificate["links"]:
        for row in link["witnesses"]:
            for reference, _ in row:
                assert reference == ["exact", 0]
    assert certificate["chain"]["breakpoints"][-1] == "3"
    result = verify_cage(instance, certificate)
    assert result["valid"] is True, result


def test_rotation_bound_must_include_lower_endpoint_v103():
    """Independent rational endpoint arithmetic isolates u-minus omission."""
    _, certificate = load_rotation_case("forged_V103")
    lower = F(0)
    upper = F(1, 16)
    center = (lower + upper) / 2
    radius = F(2)
    rho = F(certificate["intervals"][16]["rho"])
    lower_bound = 4 * radius * radius * (lower - center) * (lower - center)
    lower_bound /= (1 + lower * lower) * (1 + center * center)
    upper_bound = 4 * radius * radius * (upper - center) * (upper - center)
    upper_bound /= (1 + upper * upper) * (1 + center * center)
    assert upper_bound <= rho * rho < lower_bound
    result = assert_rejection("forged_V103", "V1", "rotation_bound")
    assert result["where"]["path"] == ["certificate", "intervals", 16, "rho"]


def test_chart_two_host_sign_must_not_be_discarded_v205():
    """False chart-2 kernels pass only when every host loses its minus sign."""
    instance, certificate = load_rotation_case("forged_V205")
    assert instance == independent_asymmetric_instance()
    _, honest = load_rotation_case("asymmetric_closed")
    for index in range(32, 64):
        forged = certificate["intervals"][index]["pieces"][1]["polygon"]
        original = honest["intervals"][index]["pieces"][1]["polygon"]
        for position, (x, y) in enumerate(forged):
            assert F(x) == -F(original[position][0])
            assert F(y) == -F(original[position][1])
    assert_rejection("forged_V205", "V2", "rotated_containment")


def test_capped_chain_interval_side_mapping_must_not_swap_v506():
    """The at=0 right witness fits I_2, not the required I_1."""
    instance, certificate = load_rotation_case("forged_V506")
    moving, obstacles = low_room()
    assert instance == instance_json(moving, obstacles)
    assert len(certificate["intervals"]) == 2
    assert certificate["caps"][0]["witnesses"][2][4][0] == ["right", 0]
    result = assert_rejection("forged_V506", "V5", "homotopy_strict")
    assert result["where"]["path"] == ["certificate", "caps", 0, "witnesses", 2, 4]


def test_homotopy_quad_must_check_its_fourth_vertex_v502():
    """The supplied region contains h_s,h_(s+1),h'_(s+1), not h'_s."""
    result = assert_rejection("forged_V502", "V5", "homotopy_strict")
